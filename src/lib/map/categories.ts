export interface TownBoard {
	id: string;
	en: string;
	gu: string;
	line: string;
	category: MapCategoryId;
	lat: number;
	lon: number;
	link?: { label: string; href: string };
	gmaps?: string;
}

/*
 * Town boards: the town's own pins, each at its surveyed coordinate taken
 * from the place's Google Maps record (linked in the popup). Live Overpass
 * markers carry exact OSM geometry behind them, surveyed within the town
 * radius only — places the community hasn't vouched for stay off the map.
 */
function gmaps(slug: string, lat: number, lon: number, fid: string, cid?: string): string {
	const data = `!4m6!3m5!1s${fid}!8m2!3d${lat}!4d${lon}${cid ? `!16${cid}` : ''}`;
	return `https://www.google.com/maps/place/${slug}/@${lat},${lon},17z/data=${data}`;
}

